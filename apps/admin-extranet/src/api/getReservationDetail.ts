import { z } from 'zod';
import { zite } from 'zitejs/db';
import { createEndpoint } from 'zitejs/backend';

export default createEndpoint({
  description: 'Get full reservation detail with related LPOs, invoices, payments and status history',
  inputSchema: z.object({ id: z.string() }),
  outputSchema: z.object({
    reservation: z.object({
      id: z.string(),
      reservationRef: z.string().nullable(),
      status: z.string().nullable(),
      hotelName: z.string().nullable(),
      destination: z.string().nullable(),
      checkinDate: z.string().nullable(),
      checkoutDate: z.string().nullable(),
      rooms: z.number().nullable(),
      adults: z.number().nullable(),
      children: z.number().nullable(),
      roomType: z.string().nullable(),
      boardBasis: z.string().nullable(),
      agentName: z.string().nullable(),
      agentCompany: z.string().nullable(),
      agentEmail: z.string().nullable(),
      agentWhatsApp: z.string().nullable(),
      netRateAed: z.number().nullable(),
      sellingRateAed: z.number().nullable(),
      vatAmountAed: z.number().nullable(),
      profitAed: z.number().nullable(),
      profitMargin: z.number().nullable(),
      agentReference: z.string().nullable(),
      supplierReference: z.string().nullable(),
      hotelConfirmationNumber: z.string().nullable(),
      hotelConfirmedAt: z.string().nullable(),
      voucherSentAt: z.string().nullable(),
      isLocked: z.boolean().nullable(),
      holdExpiresAt: z.string().nullable(),
      inquiryRef: z.string().nullable(),
      specialRequests: z.string().nullable(),
      internalNotes: z.string().nullable(),
      notesToSupplier: z.string().nullable(),
      notesToAgent: z.string().nullable(),
      currencyCode: z.string().nullable(),
      createdAt: z.string().nullable(),
    }),
    lpos: z.array(z.object({
      id: z.string(),
      lpoNumber: z.string().nullable(),
      supplierEmail: z.string().nullable(),
      sentAt: z.string().nullable(),
      lpoStatus: z.string().nullable(),
      lpoNotes: z.string().nullable(),
      createdAt: z.string().nullable(),
    })),
    invoices: z.array(z.object({
      id: z.string(),
      invoiceNumber: z.string().nullable(),
      invoiceStatus: z.string().nullable(),
      subtotalAmount: z.number().nullable(),
      vatAmount: z.number().nullable(),
      totalAmount: z.number().nullable(),
      issuedAt: z.string().nullable(),
      dueDate: z.string().nullable(),
      invoiceNotes: z.string().nullable(),
      createdAt: z.string().nullable(),
    })),
    payments: z.array(z.object({
      id: z.string(),
      paymentReference: z.string().nullable(),
      paymentStatus: z.string().nullable(),
      paymentMethod: z.string().nullable(),
      amount: z.number().nullable(),
      receivedAt: z.string().nullable(),
      paymentNotes: z.string().nullable(),
      createdAt: z.string().nullable(),
    })),
    statusEvents: z.array(z.object({
      id: z.string(),
      eventSummary: z.string().nullable(),
      fromStatus: z.string().nullable(),
      toStatus: z.string().nullable(),
      eventReason: z.string().nullable(),
      createdBy: z.string().nullable(),
      createdAt: z.string().nullable(),
    })),
  }),
  execute: async ({ input }) => {
    const r = await zite.reservations.findOne({ id: input.id });
    if (!r) throw new Error('Reservation not found');

    const [lposRes, invoicesRes, paymentsRes, eventsRes] = await Promise.all([
      zite.reservationLpOs.findAll({ filters: { reservation: input.id } }),
      zite.reservationInvoices.findAll({ filters: { reservation: input.id } }),
      zite.reservationPayments.findAll({ filters: { reservation: input.id } }),
      zite.reservationStatusEvents.findAll({ filters: { reservation: input.id } }),
    ]);

    return {
      reservation: {
        id: r.id,
        reservationRef: r.reservationRef ?? null,
        status: r.status ?? null,
        hotelName: r.hotelName ?? null,
        destination: r.destination ?? null,
        checkinDate: r.checkinDate ?? null,
        checkoutDate: r.checkoutDate ?? null,
        rooms: r.rooms ?? null,
        adults: r.adults ?? null,
        children: r.children ?? null,
        roomType: r.roomType ?? null,
        boardBasis: r.boardBasis ?? null,
        agentName: r.agentName ?? null,
        agentCompany: r.agentCompany ?? null,
        agentEmail: r.agentEmail ?? null,
        agentWhatsApp: r.agentWhatsApp ?? null,
        netRateAed: r.netRateAed ?? null,
        sellingRateAed: r.sellingRateAed ?? null,
        vatAmountAed: r.vatAmountAed ?? null,
        profitAed: r.profitAed ?? null,
        profitMargin: r.profitMargin ?? null,
        agentReference: r.agentReference ?? null,
        supplierReference: r.supplierReference ?? null,
        hotelConfirmationNumber: r.hotelConfirmationNumber ?? null,
        hotelConfirmedAt: r.hotelConfirmedAt ?? null,
        voucherSentAt: r.voucherSentAt ?? null,
        isLocked: r.isLocked ?? null,
        holdExpiresAt: r.holdExpiresAt ?? null,
        inquiryRef: r.inquiryRef ?? null,
        specialRequests: r.specialRequests ?? null,
        internalNotes: r.internalNotes ?? null,
        notesToSupplier: r.notesToSupplier ?? null,
        notesToAgent: r.notesToAgent ?? null,
        currencyCode: r.currencyCode ?? null,
        createdAt: r.createdAt ?? null,
      },
      lpos: lposRes.records.map(l => ({
        id: l.id, lpoNumber: l.lpoNumber ?? null, supplierEmail: l.supplierEmail ?? null,
        sentAt: l.sentAt ?? null, lpoStatus: l.lpoStatus ?? null, lpoNotes: l.lpoNotes ?? null, createdAt: l.createdAt ?? null,
      })),
      invoices: invoicesRes.records.map(i => ({
        id: i.id, invoiceNumber: i.invoiceNumber ?? null, invoiceStatus: i.invoiceStatus ?? null,
        subtotalAmount: i.subtotalAmount ?? null, vatAmount: i.vatAmount ?? null, totalAmount: i.totalAmount ?? null,
        issuedAt: i.issuedAt ?? null, dueDate: i.dueDate ?? null, invoiceNotes: i.invoiceNotes ?? null, createdAt: i.createdAt ?? null,
      })),
      payments: paymentsRes.records.map(p => ({
        id: p.id, paymentReference: p.paymentReference ?? null, paymentStatus: p.paymentStatus ?? null,
        paymentMethod: p.paymentMethod ?? null, amount: p.amount ?? null, receivedAt: p.receivedAt ?? null,
        paymentNotes: p.paymentNotes ?? null, createdAt: p.createdAt ?? null,
      })),
      statusEvents: eventsRes.records.map(e => ({
        id: e.id, eventSummary: e.eventSummary ?? null, fromStatus: e.fromStatus ?? null,
        toStatus: e.toStatus ?? null, eventReason: e.eventReason ?? null, createdBy: e.createdBy ?? null, createdAt: e.createdAt ?? null,
      })).sort((a, b) => (b.createdAt ?? '').localeCompare(a.createdAt ?? '')),
    };
  },
});
