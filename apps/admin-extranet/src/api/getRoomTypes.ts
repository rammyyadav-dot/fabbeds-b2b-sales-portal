import { z } from 'zod';
import { zite } from 'zitejs/db';
import { createEndpoint } from 'zitejs/backend';

const roomTypeSchema = z.object({
  id: z.string(),
  roomTypeName: z.string().optional(),
  hotel: z.union([z.array(z.string()), z.string()]).optional(),
  internalCode: z.string().optional(),
  maxOccupancy: z.number().optional(),
  mealPlan: z.string().optional(),
  description: z.string().optional(),
  beddingType: z.string().optional(),
  views: z.string().optional(),
  inclusions: z.string().optional(),
  sellEnabled: z.boolean().optional(),
  onRequestOnly: z.boolean().optional(),
  maxAdults: z.number().optional(),
  maxChildren: z.number().optional(),
  maxAdultsWithChildren: z.number().optional(),
  minTotalOccupancy: z.number().optional(),
  minAdultsRequired: z.number().optional(),
  extraBedCountsTowardTotal: z.boolean().optional(),
  eventMaxOccupancy: z.number().optional(),
  lockAfterBooking: z.boolean().optional(),
  childAllowed: z.boolean().optional(),
  childAgeFrom: z.number().optional(),
  childAgeTo: z.number().optional(),
  childAgeFreeUpTo: z.number().optional(),
  childAgeAdultFrom: z.number().optional(),
  extraBedAllowed: z.boolean().optional(),
  maxExtraBeds: z.number().optional(),
  adultExtraBedAvailable: z.boolean().optional(),
  roomTypeCode: z.string().optional(),
  baseOccupancy: z.number().optional(),
  childPolicyId: z.string().optional(),
  status: z.string().optional(),
});

export default createEndpoint({
  description: 'Get room types for a hotel',
  inputSchema: z.object({ hotelId: z.string().optional() }),
  outputSchema: z.object({ roomTypes: z.array(roomTypeSchema) }),
  execute: async ({ input }) => {
    const filters = input.hotelId ? { hotel: input.hotelId } : {};
    const result = await zite.roomTypes.findAll({ filters, limit: 500 });
    return {
      roomTypes: result.records.map(r => ({
        id: r.id,
        roomTypeName: r.roomTypeName,
        hotel: r.hotel,
        internalCode: r.internalCode,
        maxOccupancy: r.maxOccupancy,
        mealPlan: r.mealPlan,
        description: r.description,
        beddingType: r.beddingType,
        views: r.views,
        inclusions: r.inclusions,
        sellEnabled: r.sellEnabled,
        onRequestOnly: r.onRequestOnly,
        maxAdults: r.maxAdults,
        maxChildren: r.maxChildren,
        maxAdultsWithChildren: r.maxAdultsWithChildren,
        minTotalOccupancy: r.minTotalOccupancy,
        minAdultsRequired: r.minAdultsRequired,
        extraBedCountsTowardTotal: r.extraBedCountsTowardTotal,
        eventMaxOccupancy: r.eventMaxOccupancy,
        lockAfterBooking: r.lockAfterBooking,
        childAllowed: r.childAllowed,
        childAgeFrom: r.childAgeFrom,
        childAgeTo: r.childAgeTo,
        childAgeFreeUpTo: r.childAgeFreeUpTo,
        childAgeAdultFrom: r.childAgeAdultFrom,
        extraBedAllowed: r.extraBedAllowed,
        maxExtraBeds: r.maxExtraBeds,
        adultExtraBedAvailable: r.adultExtraBedAvailable,
        roomTypeCode: r.roomTypeCode,
        baseOccupancy: r.baseOccupancy,
        childPolicyId: r.childPolicyId,
        status: r.status,
      })),
    };
  },
});
